def _maxabs(got, exp):
    return float(np.max(np.abs(np.asarray(got, float) - np.asarray(exp, float))))


def _blocks(pairs):
    return np.concatenate([np.full(int(s), float(v)) for s, v in pairs])


# ---------------- NaN-hostile scoring toolkit (v1.2) ----------------
# Python's max() keeps the CURRENT value when the comparison is False, so both
# `max(worst, abs(nan - x))` and `max(worst, nan)` silently return `worst`: a NaN sentinel
# used to look like "no difference".  Every difference below therefore maps a non-finite
# operand to +inf, and every accumulator also counts the non-finite values.  Python's
# builtin max() is only ever fed these +inf-safe diffs.
def _fin(v):
    try:
        return math.isfinite(float(v))
    except Exception:
        return False


def _ndiff(g, e):
    """|g - e| with any non-finite operand mapped to +inf (never NaN, never plain 0)."""
    if not (_fin(g) and _fin(e)):
        return float("inf")
    return abs(float(g) - float(e))


def _score_vals(got, exp):
    """Score a short tuple of produced values against expectations -> (worst, nbad)."""
    worst, nbad = 0.0, 0
    for g, e in zip(got, exp):
        if not (_fin(g) and _fin(e)):
            nbad += 1
        worst = max(worst, _ndiff(g, e))
    return worst, nbad


def pair_ref(r, a):
    """[DEF] brute-force reference for a count pair: (PSI, base-2 JSD)."""
    return (ref_psi(r, a), ref_js(r, a))


def _scan_pairs(fn, fixtures, oracles):
    """Run fn over count fixtures, score it against every oracle, and return
    (worst, nbad, n).  Non-finite operand -> +inf and nbad += 1, so an always-NaN fn
    can never pass and the probe below can verify that on the same code path."""
    worst, nbad, n = 0.0, 0, 0
    for r, a in fixtures:
        g = fn(r, a)
        for orc in oracles:
            e = orc(r, a)
            w, b = _score_vals((g[0], g[1]), (e[0], e[1]))
            worst = max(worst, w)
            nbad += b
        n += 1
    return worst, nbad, n


