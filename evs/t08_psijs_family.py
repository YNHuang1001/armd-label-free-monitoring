def _src_const(path, name):
    """Read ONE top-level constant verbatim (column-0 assignment) from a production file."""
    for ln in L.read_lines(path):
        if not ln.strip() or ln[:1].isspace():
            continue
        if not re.match(r"^[A-Za-z_][A-Za-z0-9_]*(\s*,\s*[A-Za-z_][A-Za-z0-9_]*)*\s*=", ln):
            continue
        if re.search(r"\b" + re.escape(name) + r"\b", ln.split("=")[0]):
            ns = {}
            exec(ln, ns)
            if name in ns:
                return ns[name], ln
    raise LookupError("top-level constant %r not found in %s" % (name, path))


def _src_list(path, name):
    """Read a top-level list literal verbatim (may span several lines)."""
    lines = L.read_lines(path)
    for i, ln in enumerate(lines):
        if re.match(r"^%s\s*=\s*\[" % re.escape(name), ln):
            buf, depth = [], 0
            for ln2 in lines[i:]:
                buf.append(ln2)
                depth += ln2.count("[") - ln2.count("]")
                if depth <= 0:
                    break
            ns = {}
            exec("\n".join(buf), ns)
            return ns[name]
    raise LookupError("top-level list %r not found in %s" % (name, path))


